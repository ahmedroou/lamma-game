def science_pairs():
    out=[]
    for line in SCIENCE_TOPICS.splitlines():
        id,topic=line.split('|');s=sources[id]
        # Reading this archive is deterministic and preserves the actual
        # institutional motivation used in authoring; no invented references.
        assert s['sourceText'].strip() and s['motivation'].strip()
        out.append(dict(left=rows[id][2],right=topic,kind=s['category'],year=s['year'],source=s['url'],motivation=s['motivation']))
    return out

